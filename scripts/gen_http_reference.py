"""Generate the HTTP API reference page of the docs site from the committed OpenAPI document.

Reads ``ui/openapi/openapi.json`` (the merged platform document, itself drift-checked by
``scripts/export_openapi.py --check``) and ``tests/repo/authz_matrix.golden.json`` (generated from
the live route policies), joins them on ``operationId`` and writes one table per tag to
``docs/user/reference/http-api.md``. Only operation summaries are used, never descriptions, so the
page carries no design notes. Standard library only.

    uv run python scripts/gen_http_reference.py          write the page
    uv run python scripts/gen_http_reference.py --check  exit 1 when the committed page is stale

``--check`` renders in memory and never writes.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "ui" / "openapi" / "openapi.json"
MATRIX = ROOT / "tests" / "repo" / "authz_matrix.golden.json"
TARGET = ROOT / "docs" / "user" / "reference" / "http-api.md"
METHODS = ("get", "put", "post", "delete", "patch")
ROUTE_SUFFIX = " Route"
STALE_HINT = (
    "docs/user/reference/http-api.md is stale: run `uv run python scripts/gen_http_reference.py`"
)
HEADER = [
    "# HTTP API reference",
    "",
    "<!-- Generated by scripts/gen_http_reference.py from ui/openapi/openapi.json and",
    "tests/repo/authz_matrix.golden.json. Do not edit. -->",
    "",
    "Every operation of the Contractum HTTP API, grouped by module. A running platform serves the",
    "interactive reference, with every request and response schema, at `/api/v1/docs/`, and the",
    "OpenAPI document at `/api/v1/openapi.json`.",
    "",
    "- **Permission** is the permission the route checks. `public` means it checks no permission.",
    "- **Sign-in** says whether the call needs a bearer token.",
    "",
]


def load_spec(path: Path = SPEC) -> dict[str, Any]:
    doc: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return doc


def load_matrix(path: Path = MATRIX) -> dict[str, Any]:
    doc: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return doc


def _cell(text: str) -> str:
    """Make ``text`` safe for one Markdown table cell (escape each pipe exactly once)."""
    return " ".join(text.split()).replace("|", "\\|")


def _summary(op: dict[str, Any]) -> str:
    summary = str(op.get("summary") or "").strip()
    return summary.removesuffix(ROUTE_SUFFIX)


def _permission(entry: dict[str, Any] | None) -> str:
    if entry is None:
        return "-"
    permission = entry.get("permission")
    if permission:
        return f"`{permission}`"
    return "public" if entry.get("target") == "public" else "-"


def render(spec: dict[str, Any], matrix: dict[str, Any]) -> str:
    """Render the reference page: one table per tag, rows sorted by path, then method."""
    by_tag: dict[str, list[tuple[str, int, str]]] = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in METHODS:
                continue
            tag = str((op.get("tags") or ["other"])[0])
            sign_in = "no" if op.get("security") == [] else "yes"
            permission = _permission(matrix.get(str(op.get("operationId"))))
            row = (
                f"| `{method.upper()}` | `{path}` | {_cell(_summary(op))} "
                f"| {permission} | {sign_in} |"
            )
            by_tag.setdefault(tag, []).append((path, METHODS.index(method), row))
    out = list(HEADER)
    for tag in sorted(by_tag):
        out += [
            f"## {tag.capitalize()}",
            "",
            "| Method | Path | Summary | Permission | Sign-in |",
            "| --- | --- | --- | --- | --- |",
        ]
        out += [row for _, _, row in sorted(by_tag[tag])]
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def write_or_check(rendered: str, target: Path = TARGET, *, check: bool) -> int:
    """Write ``rendered`` to ``target``; with ``check``, return 1 when the bytes differ."""
    if check:
        if not target.exists() or target.read_bytes() != rendered.encode("utf-8"):
            print(STALE_HINT, file=sys.stderr)
            return 1
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(rendered.encode("utf-8"))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the HTTP API reference page.")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when the committed page differs; write nothing"
    )
    args = parser.parse_args(argv)
    return write_or_check(render(load_spec(), load_matrix()), check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
