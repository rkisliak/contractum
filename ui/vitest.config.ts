import { resolve } from "node:path";
import react from "@vitejs/plugin-react";
import { defineConfig } from "vitest/config";

// Measured floor (percent), set from the last full-gate coverage run.
const COVERAGE_THRESHOLDS = {
  lines: 99,
  statements: 99,
  functions: 99,
  branches: 96,
};

export default defineConfig({
  plugins: [react()],
  resolve: {
    alias: { "@": resolve(import.meta.dirname, "src") },
  },
  test: {
    environment: "jsdom",
    setupFiles: ["src/test/setup.ts"],
    // Process CSS modules so class-name lookups behave as in the build.
    css: true,
    include: ["src/**/*.test.{ts,tsx}"],
    // Screen tests mount the whole shell (router, query client, msw). They take 0.5 to 1.5 s
    // alone, but under v8 coverage with every worker busy on a loaded host the 5 s default timed
    // out 115 healthy tests in the full gate. 30 s still catches a test that truly hangs.
    testTimeout: 30_000,
    hookTimeout: 30_000,
    // One worker per core starves every test when the machine is shared (the stack, other
    // projects, the Docker VM); four workers finish as fast and keep each render well inside time.
    maxWorkers: 4,
    // `pnpm test:coverage` (the full gate, CI_FULL=1 scripts/ci.sh). Thresholds are the measured
    // floor of the last full-gate coverage run; raise them when coverage rises, never lower them.
    coverage: {
      provider: "v8",
      include: ["src/**/*.{ts,tsx}"],
      exclude: [
        "src/**/*.test.{ts,tsx}",
        "src/test/**", // test helpers (renderApp, msw handlers, setup)
        "src/routeTree.gen.ts", // generated by the router plugin
        "src/api/schema.gen.ts", // generated types only
        "src/**/*.d.ts",
      ],
      reporter: [
        "text-summary",
        "json-summary",
        "text",
        // coverage/lcov.info for SonarQube (sonar-project.properties): paths relative to the
        // repo root (ui/src/...), so the scanner maps them from its base directory.
        ["lcovonly", { projectRoot: resolve(import.meta.dirname, "..") }],
      ],
      reportsDirectory: "coverage",
      thresholds: COVERAGE_THRESHOLDS,
    },
  },
});
