"""Generate the CLI and SDK API reference pages of the docs site.

``docs/user/reference/cli.md`` is rendered structurally from the ``contractum`` click command tree
(usage pieces, arguments, options and the help text), never from ``get_help()``, so the output does
not depend on the terminal width. The order is deterministic: commands sorted by name, parameters
in declaration order.

``docs/user/reference/sdk-api.md`` is a mkdocstrings page. The package exports its names lazily,
so mkdocstrings renders nothing without an explicit ``members:`` list, and a wrong name there
builds silently. The list is therefore generated from ``contractum.__all__`` (minus
``__version__``): every public name renders, and nothing private or generated does.

Usage (run from ``clients/python``)::

    uv run python scripts/gen_reference.py            write the page
    uv run python scripts/gen_reference.py --check    exit 1 when the committed page is stale

``--check`` renders in memory and never writes.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from collections.abc import Mapping
from pathlib import Path

import click

SDK_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = Path(__file__).resolve().parents[3]
REFERENCE_DIR = REPO_ROOT / "docs" / "user" / "reference"
CLI_PAGE = REFERENCE_DIR / "cli.md"
SDK_API_PAGE = REFERENCE_DIR / "sdk-api.md"

GENERATED_NOTE = "<!-- Generated by clients/python/scripts/gen_reference.py. Do not edit. -->"
STALE_HINT = (
    "docs/user/reference is stale: run `uv run python scripts/gen_reference.py` in clients/python"
)
MAX_HEADING_LEVEL = 4
# A bare URL in help text (not already in a code span or an autolink), without trailing punctuation.
BARE_URL = re.compile(r"(?<![`<(])\bhttps?://[^\s`<>()]*[^\s`<>().,;:!?]")


def _cell(text: str) -> str:
    """Make ``text`` safe for one Markdown table cell (escape each pipe exactly once)."""
    return text.replace("\n", " ").replace("|", "\\|")


def _help_paragraphs(text: str | None) -> list[str]:
    """Split click help text into paragraphs, honouring click's ``\\f`` cut and ``\\b`` marker."""
    if not text:
        return []
    text = click.unstyle(text).split("\f", 1)[0]
    paragraphs = []
    for block in text.strip().split("\n\n"):
        lines = [line.strip() for line in block.splitlines() if line.strip() != "\b"]
        joined = " ".join(line for line in lines if line)
        if joined:
            # Help text shows example URLs; a code span keeps them from reading as links.
            paragraphs.append(BARE_URL.sub(lambda match: f"`{match.group(0)}`", joined))
    return paragraphs


def _range(param_type: click.IntRange | click.FloatRange) -> str:
    low, high = param_type.min, param_type.max
    if low is not None and high is not None:
        return f"{low} to {high}"
    if low is not None:
        return f"{'>' if param_type.min_open else '>='} {low}"
    if high is not None:
        return f"{'<' if param_type.max_open else '<='} {high}"
    return ""


def _type(param: click.Parameter) -> str:
    """Describe what an option or argument takes: flag, choices, metavar or type name."""
    if isinstance(param, click.Option) and param.is_flag:
        return "flag"
    param_type = param.type
    if isinstance(param_type, click.Choice):
        return ", ".join(f"`{choice}`" for choice in param_type.choices)
    if param.metavar:
        return param.metavar
    if isinstance(param_type, click.IntRange | click.FloatRange):
        base = "INTEGER" if isinstance(param_type, click.IntRange) else "NUMBER"
        bounds = _range(param_type)
        return f"{base}, {bounds}" if bounds else base
    return param_type.name.upper()


def _default(option: click.Option) -> str:
    """Return the shown default of an option, or an empty string when click would not show one."""
    if option.is_flag or not option.show_default:
        return ""
    if isinstance(option.show_default, str):
        return option.show_default
    value = option.default
    if value is None or callable(value) or not isinstance(value, str | int | float | os.PathLike):
        return ""
    return f"`{os.fspath(value) if isinstance(value, os.PathLike) else value}`"


def _render_command(
    command: click.Command,
    path: list[str],
    parent: click.Context | None,
    out: list[str],
    level: int,
) -> None:
    name = " ".join(path)
    out += [f"{'#' * level} `{name}`", ""]
    for paragraph in _help_paragraphs(command.help):
        out += [paragraph, ""]
    with click.Context(command, info_name=path[-1], parent=parent) as ctx:
        usage = " ".join(command.collect_usage_pieces(ctx))
        out += ["```text", f"{name} {usage}", "```", ""]
        arguments = [p for p in command.params if isinstance(p, click.Argument)]
        options = [p for p in command.params if isinstance(p, click.Option) and not p.hidden]
        if arguments:
            out += ["| Argument | Required |", "| --- | --- |"]
            out += [
                f"| `{a.human_readable_name}` | {'yes' if a.required else 'no'} |"
                for a in arguments
            ]
            out.append("")
        if options:
            out += ["| Option | Takes | Default | Description |", "| --- | --- | --- | --- |"]
            for option in options:
                names = ", ".join(f"`{n}`" for n in [*option.opts, *option.secondary_opts])
                description = " ".join(_help_paragraphs(option.help)[:1])
                out.append(
                    f"| {names} | {_cell(_type(option))} | {_cell(_default(option))} "
                    f"| {_cell(description)} |"
                )
            out.append("")
        if isinstance(command, click.Group):
            for child_name in command.list_commands(ctx):
                child = command.get_command(ctx, child_name)
                if child is None or child.hidden:
                    continue
                child_level = min(level + 1, MAX_HEADING_LEVEL)
                _render_command(child, [*path, child_name], ctx, out, child_level)


def render_cli(root: click.Command, prog_name: str = "contractum") -> str:
    """Render the whole command tree below ``root`` as one Markdown page."""
    out = [
        "# CLI reference",
        "",
        GENERATED_NOTE,
        "",
        f"Every `{prog_name}` command, its arguments and its options. Global options go before",
        f"the command name, for example `{prog_name} --profile prod list`. Every command also",
        "accepts `--help`.",
        "",
    ]
    _render_command(root, [prog_name], None, out, 2)
    return "\n".join(out).rstrip("\n") + "\n"


def public_names() -> list[str]:
    """The public ``contractum`` API: ``__all__`` without ``__version__``, sorted."""
    import contractum

    return sorted(name for name in contractum.__all__ if name != "__version__")


def render_sdk_api(names: list[str]) -> str:
    """Render the mkdocstrings page for ``names`` of the ``contractum`` package."""
    out = [
        "# SDK API reference",
        "",
        GENERATED_NOTE,
        "",
        "The public Python API of the `contractum` package: everything you can import from it.",
        "",
        "::: contractum",
        "    options:",
        "      show_root_heading: true",
        "      members:",
    ]
    out += [f"        - {name}" for name in names]
    return "\n".join(out) + "\n"


def render_pages() -> dict[Path, str]:
    """Render every generated reference page, keyed by its target path."""
    from contractum.cli import cli

    return {CLI_PAGE: render_cli(cli), SDK_API_PAGE: render_sdk_api(public_names())}


def write_or_check(pages: Mapping[Path, str], *, check: bool) -> int:
    """Write ``pages``; with ``check``, compare bytes instead and return 1 on any difference."""
    if check:
        stale = [
            path
            for path, text in pages.items()
            if not path.exists() or path.read_bytes() != text.encode("utf-8")
        ]
        for path in stale:
            print(f"stale: {path}", file=sys.stderr)
        if stale:
            print(STALE_HINT, file=sys.stderr)
            return 1
        return 0
    for path, text in pages.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the CLI and SDK API reference pages.")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when a committed page differs; write nothing"
    )
    args = parser.parse_args(argv)
    return write_or_check(render_pages(), check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
