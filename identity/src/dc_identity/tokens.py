"""Access-token issuing: the locked claim set and nothing else (D-03, D-05).

Claims: iss, sub, aud, iat, nbf, exp, jti, ptype, scope, name. Authority never travels in the
token: identity's role_assignments table is the only source of permissions.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from typing import TYPE_CHECKING

import jwt
import uuid_utils.compat as uuid_compat

if TYPE_CHECKING:
    from dc_identity.keys import SigningKeys
    from dc_identity.models import User
    from dc_identity.settings import IdentitySettings


@dataclass(frozen=True)
class IssuedToken:
    token: str
    expires_in: int
    scope: str
    jti: str


def issue_access_token(
    keys: SigningKeys,
    *,
    user: User,
    scope: str,
    ttl_s: int,
    settings: IdentitySettings,
    jti: str | None = None,
) -> IssuedToken:
    """Sign an access token. ``jti`` is pre-generated by login and refresh, which store it on the
    session row so the caller's own session can be recognised; the claim set is unchanged."""
    now = int(time.time())
    jti = jti if jti is not None else str(uuid_compat.uuid7())
    claims = {
        "iss": settings.local_issuer,
        "sub": str(user.id),
        "aud": settings.token_audience,
        "iat": now,
        "nbf": now,
        "exp": now + ttl_s,
        "jti": jti,
        "ptype": "user",
        "scope": scope,
        "name": user.display_name,
    }
    token = jwt.encode(claims, keys.private_pem, algorithm="RS256", headers={"kid": keys.kid})
    return IssuedToken(token=token, expires_in=ttl_s, scope=scope, jti=jti)
